std::vector<std::string> names() {
    std::vector<std::string> out;
    for (const Theme& t : all()) out.push_back(t.name);
    return out;
}

const Theme* find(const std::string& name) {
    for (const Theme& t : all()) {
        if (strcasecmp(t.name, name.c_str()) == 0) return &t;
    }
    return nullptr;
}

bool parse_hex(const std::string& text, Rgb& out) {
    if (text.size() != 4 && text.size() != 7) return false;
    if (text[0] != '#') return false;
    for (size_t i = 1; i < text.size(); ++i) {
        if (!std::isxdigit(static_cast<unsigned char>(text[i]))) return false;
    }
    auto hex = [](char c) { return std::isdigit(static_cast<unsigned char>(c)) ? c - '0' : (std::tolower(c) - 'a' + 10); };
    if (text.size() == 4) {
        out = { static_cast<uint8_t>(hex(text[1]) * 17), static_cast<uint8_t>(hex(text[2]) * 17),
                static_cast<uint8_t>(hex(text[3]) * 17) };
    } else {
        out = { static_cast<uint8_t>(hex(text[1]) * 16 + hex(text[2])),
                static_cast<uint8_t>(hex(text[3]) * 16 + hex(text[4])),
                static_cast<uint8_t>(hex(text[5]) * 16 + hex(text[6])) };
    }
    return true;
}

std::string to_hex(const Rgb& c) {
    char buf[8];
    std::snprintf(buf, sizeof(buf), "#%02x%02x%02x", c.r, c.g, c.b);
    return buf;
}

